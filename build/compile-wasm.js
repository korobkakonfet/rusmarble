import fs from 'fs';
import path from 'path';
import wabtFactory from 'wabt';

const sourceDir = path.resolve('src/wasm');
const outputDir = path.resolve('src/generated');

const targets = [
  {
    source: path.join(sourceDir, 'templatePalette.wat'),
    output: path.join(outputDir, 'templatePaletteWasmBytes.js'),
    exportName: 'templatePaletteWasmBytes',
  },
  {
    source: path.join(sourceDir, 'findNearestUnpainted.wat'),
    output: path.join(outputDir, 'findNearestUnpaintedWasmBytes.js'),
    exportName: 'findNearestUnpaintedWasmBytes',
  },
  {
    source: path.join(sourceDir, 'templateSampleExtract.wat'),
    output: path.join(outputDir, 'templateSampleExtractWasmBytes.js'),
    exportName: 'templateSampleExtractWasmBytes',
  },
  {
    source: path.join(sourceDir, 'collectProgress.wat'),
    output: path.join(outputDir, 'collectProgressWasmBytes.js'),
    exportName: 'collectProgressWasmBytes',
  },
  {
    source: path.join(sourceDir, 'filterBitmapPixels.wat'),
    output: path.join(outputDir, 'filterBitmapPixelsWasmBytes.js'),
    exportName: 'filterBitmapPixelsWasmBytes',
  },
];

const formatUint8Array = (bytes) => {
  const values = Array.from(bytes, (value) => String(value));
  const chunks = [];
  for (let index = 0; index < values.length; index += 24) {
    chunks.push(`  ${values.slice(index, index + 24).join(', ')}`);
  }
  return `new Uint8Array([\n${chunks.join(',\n')}\n])`;
};

async function main() {
  fs.mkdirSync(outputDir, { recursive: true });
  const wabt = await wabtFactory();

  for (const target of targets) {
    const watSource = fs.readFileSync(target.source, 'utf8');
    const parsed = wabt.parseWat(path.basename(target.source), watSource);
    const { buffer } = parsed.toBinary({
      log: false,
      write_debug_names: false,
    });
    const code = `// Generated by build/compile-wasm.js from ${path.relative(process.cwd(), target.source)}\nexport const ${target.exportName} = ${formatUint8Array(buffer)};\n`;
    fs.writeFileSync(target.output, code, 'utf8');
  }
}

main().catch((error) => {
  console.error('Failed to compile WASM assets:', error);
  process.exitCode = 1;
});
