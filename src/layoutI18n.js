const interpolate = (text, params = {}) => String(text).replace(/\{(\w+)\}/g, (_, key) => String(params?.[key] ?? ''));

export const translateLayout = (language, key, params = {}) => {
  const normalized = normalizeLayoutLanguage(language);
  const dictionary = translations[normalized] || translations.en;
  const fallback = translations.en[key];
  const value = dictionary[key] ?? fallback ?? key;
  return interpolate(value, params);
};

export const getLayoutThemeLabel = (language, value) => translateLayout(language, `layoutTheme.${String(value ?? '').toLowerCase()}`);

export const getTemplateDisplayLabel = (language, value) => translateLayout(language, `templateDisplay.${String(value ?? '').toLowerCase()}`);

export const getTemplateCreateModeLabel = (language, value) => {
  const normalized = String(value ?? '').toLowerCase();
  if (!normalized) return translateLayout(language, 'templates.create.placeholder');
  if (normalized === 'image') return translateLayout(language, 'templates.create.image');
  if (normalized === 'remote-name') return translateLayout(language, 'templates.create.remote');
  if (normalized === 'text') return translateLayout(language, 'templates.create.text');
  if (normalized === 'russian-flag') return translateLayout(language, 'templates.create.flag');
  if (normalized === 'time-archive') return translateLayout(language, 'templates.create.archive');
  return normalized;
};

export const getChatBanTypeLabel = (language, value) => translateLayout(language, `chat.banType.${String(value ?? '').toLowerCase()}`);

export const getColorSortLabel = (language, key, direction) => {
  const sortLabel = translateLayout(language, `sort.${String(key ?? '').toLowerCase()}`);
  const directionLabel = translateLayout(language, `sort.${String(direction ?? '').toLowerCase()}`);
  return `${sortLabel} (${directionLabel})`;
};
